#graphs generated by gemini
disp = ConfusionMatrixDisplay.from_estimator(
    knn, 
    X_test, 
    y_test, 
    cmap=plt.cm.Blues
)
disp.ax_.set_title("KNN Confusion Matrix")

# Save as PNG with high resolution and tight borders
plt.savefig("knn_confusion_matrix.png", dpi=300, bbox_inches='tight')
plt.close() # Closes the figure to prevent overlapping plots

# ==========================================
# 2. Decision Boundary Plot
# ==========================================
plt.figure(figsize=(8, 6))
disp_boundary = DecisionBoundaryDisplay.from_estimator(
    knn,
    X_train,
    response_method="predict",
    cmap=plt.cm.coolwarm,
    alpha=0.5,
    xlabel="Feature 1",
    ylabel="Feature 2"
)

disp_boundary.ax_.scatter(
    X_train.iloc[:, 0], 
    X_train.iloc[:, 1], 
    c=y_train,             
    edgecolor="k",
    cmap=plt.cm.coolwarm
)

plt.title("KNN Decision Boundary")

# Save as PNG with high resolution and tight borders
plt.savefig("knn_decision_boundary.png", dpi=300, bbox_inches='tight')
plt.close()


