import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import ConfusionMatrixDisplay
from sklearn.inspection import DecisionBoundaryDisplay
from sklearn.model_selection import cross_val_score
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split
from sklearn import metrics

emails = pd.read_csv("../../data/processed/email_phishing_data_man.csv").dropna()
X = emails.drop(columns=["label"])
X_specific = emails[["num_words", "num_unique_words", "num_stopwords", "num_spelling_errors"]]
y = emails[["label"]]
scaler = StandardScaler()


X_train, X_test, y_train, y_test = train_test_split(X, np.ravel(y), test_size=0.3)
rfModel = RandomForestClassifier()
rfModel.fit(X, np.ravel(y))
scaler.fit_transform(X_train)
scaler.transform(X_test)

rfModel1 = RandomForestClassifier(criterion="entropy")
rfModel1.fit(X_train, y_train)
predict1 = rfModel1.predict(X_test)
recall1 = metrics.recall_score(y_test, predict1)
accuracy1 = metrics.accuracy_score(y_test, predict1)
print("Acc + Recall for 1: " + str(accuracy1) + " " + str(recall1))


