import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from pathlib import Path

from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.model_selection import train_test_split
from sklearn.inspection import permutation_importance
from sklearn.metrics import (
    average_precision_score, classification_report,
    precision_recall_curve, ConfusionMatrixDisplay, PrecisionRecallDisplay,
)
HERE = Path(__file__).resolve().parent / "reports"
DATA = Path(__file__).resolve().parents[2] / "data" / "raw" / "email_phishing_data.csv"

emails = pd.read_csv(DATA).dropna().drop_duplicates()
print(emails.shape)
print(emails["label"].value_counts())

w = emails["num_words"].clip(lower=1)
emails["unique_ratio"]    = emails["num_unique_words"] / w
emails["stopword_ratio"]  = emails["num_stopwords"] / w
emails["spelling_ratio"]  = emails["num_spelling_errors"] / w
emails["links_per_word"]  = emails["num_links"] / w
emails["urgent_per_word"] = emails["num_urgent_keywords"] / w
emails["has_link"]        = (emails["num_links"] > 0).astype(int)
emails["has_email_addr"]  = (emails["num_email_addresses"] > 0).astype(int)
emails["log_words"]       = np.log1p(emails["num_words"])

X = emails.drop(columns=["label"])
y = emails["label"]

#train 60%, validation 20%, test 20%

X_tmp, X_test, y_tmp, y_test = train_test_split(X, y, test_size=0.2, random_state = 67, stratify = y)
X_train, X_val, y_train, y_val = train_test_split(X_tmp, y_tmp, test_size = 0.25, random_state = 67, stratify = y_tmp)

HGBC = HistGradientBoostingClassifier(class_weight = "balanced", random_state = 67)
HGBC.fit(X_train, y_train)


#Validation, Test, and Cahrts, generated by Claude

# ---- Pick a threshold on the VALIDATION set (target: recall >= 0.80) ----
val_probs = HGBC.predict_proba(X_val)[:, 1]
print("Val PR-AUC:", round(average_precision_score(y_val, val_probs), 4), "| chance level:", round(y_val.mean(), 4))

prec, rec, thr = precision_recall_curve(y_val, val_probs)
ok = rec[:-1] >= 0.80
threshold = thr[ok][np.argmax(prec[:-1][ok])] if ok.any() else 0.5
print("Chosen threshold:", round(float(threshold), 4))

# ---- Evaluate on the TEST set, once ----
test_probs = HGBC.predict_proba(X_test)[:, 1]
y_pred = (test_probs >= threshold).astype(int)
print("Test PR-AUC:", round(average_precision_score(y_test, test_probs), 4), "| chance level:", round(y_test.mean(), 4))
print(classification_report(y_test, y_pred, digits=3))

# ---- Chart 1: confusion matrix ----
ConfusionMatrixDisplay.from_predictions(y_test, y_pred, cmap="Blues")
plt.title("Gradient boosting: confusion matrix")
plt.savefig(HERE / "confusion_matrix.png", dpi=150, bbox_inches="tight")
plt.show()

# ---- Chart 2: precision-recall curve ----
PrecisionRecallDisplay.from_predictions(y_test, test_probs)
plt.axhline(y_test.mean(), linestyle="--", color="gray", label="chance")
plt.legend()
plt.title("Precision-recall curve (test set)")
plt.savefig(HERE / "pr_curve.png", dpi=150, bbox_inches="tight")
plt.show()

# ---- Chart 3: which features matter (permutation importance, validation set) ----
r = permutation_importance(HGBC, X_val, y_val, scoring="average_precision", n_repeats=5, random_state=42)
imp = pd.Series(r.importances_mean, index=X_val.columns).sort_values()
imp.plot(kind="barh", figsize=(8, 5))
plt.xlabel("Drop in PR-AUC when the feature is shuffled")
plt.title("Feature importance")
plt.tight_layout()
plt.savefig(HERE / "feature_importance.png", dpi=150, bbox_inches="tight")
plt.show()